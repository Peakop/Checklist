export function sectionsFor(code){
  const sheet = isSheet(code), img = DIAGRAM_IMG.has(code);
  // ไฟล์ภาพแผนภาพไม่มีหน้ากระดาษ ตัวพิมพ์ หรือเลขหน้า และเวอร์ชันเทียบกับเอกสาร Version Control ของแผนภาพแทน
  const version = img ? Object.assign({}, SEC.version, {items:[...SEC.version.items.slice(0, 4), 'เวอร์ชันในชื่อไฟล์ตรงกับเวอร์ชันล่าสุดในเอกสาร Version Control (VC) ของแผนภาพนี้']}) : SEC.version;
  // UCDS และ VC เป็นตารางล้วน ไม่มีหัวข้อระดับต่าง ๆ และไม่มีบทนำ
  const layout = sheet ? [SEC.sheet] : img ? []
    : code === 'UCDS' ? [SEC.page, pick(SEC.font, [0, 4]), pick(SEC.pagenum, [1, 2])]
    : code === 'VC' ? [SEC.page, pick(SEC.font, [0, 1, 4]), pick(SEC.spacing, [1]), pick(SEC.pagenum, [1, 2])]
    : [SEC.page, SEC.font, pick(SEC.spacing, [1, 2]), SEC.pagenum];
  const base = [SEC.naming(code), version, ...layout];
  const front = LONG.has(code) ? [SEC.front] : [];
  const content = contentFor(code);
  let extra;
  if (sheet) extra = [content];
  else if (INVITE.has(code)) extra = [SEC.invite, content, SEC.writing, SEC.lang];
  else if (AGENDA.has(code)) extra = [SEC.invite, SEC.agendaDS, content, SEC.writing, SEC.lang, SEC.table];
  else if (REPORT.has(code)) extra = [SEC.report, content, SEC.writing, SEC.lang, SEC.table];
  else if (img) extra = [DIAGRAM[code], content];
  else if (code === 'UCDS') extra = [DIAGRAM.UCDS, content, SEC.lang, pick(SEC.table, [0, 2, 3])];
  else if (code === 'VC') extra = [content, SEC.lang, SEC.table];
  else if (code === 'DD') extra = [DIAGRAM.DD, content, SEC.lang, SEC.table, SEC.image];
  else if (code === 'RP') extra = [DIAGRAM.RP, content, SEC.image];
  else if (CHART.has(code)) extra = [content, SEC.lang, SEC.table, SEC.image];
  else extra = [content, SEC.writing, SEC.lang, SEC.table, SEC.image];
  return base.concat(front, extra.filter(Boolean));
}

